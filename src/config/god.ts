/**
 * ============================================================
 *  神の妨害と天才（手動調整用）
 * ============================================================
 * 神の妨害: 塔が一定の高さを超えると、ランダムなタイミングで起きる。
 *   雷       … 命中したトラップを停止させる（停止したトラップは撤去するしかない）
 *   言語混乱 … 次の3種類がある（天才で解決できる）
 *     ・言語   … UIの文字が別の言語のような文字に変わる
 *     ・数値   … 所持ポイントやコストなど、一部の数値の表示がでたらめになる
 *     ・作業停止 … 作業員の手が止まり、塔が伸びなくなる（一定時間で再開、天才ですぐ再開）
 *   技術封印 … 特定のトラップが製造できなくなる（天才で再発明できる）
 *
 * 天才: 10階ごとに1人やってくる。ドラッグして使う（1回で消費）。
 *   妨害欄の妨害へ … その妨害を解決（言語混乱の統一・トラップの再発明・作業再開）
 *   作業員へ       … 作業停止中なら再開、そうでなければ一定時間作業を早める
 *   トラップへ     … そのトラップの種類を強化（技術促進）。封印中のトラップなら再発明
 */

